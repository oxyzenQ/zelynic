/// The active theme state. Written ONLY by the eagle-eyes key
/// handler (`t` inside the alt screen); every other surface reads
/// the default and never knows themes exist.
static ACTIVE: AtomicU8 = AtomicU8::new(0);

/// The active theme.
pub(crate) fn active() -> Theme {
    match ACTIVE.load(Ordering::Relaxed) {
        1 => Theme::NightCyber,
        2 => Theme::Forest,
        3 => Theme::Spaceflight,
        4 => Theme::Carbon,
        5 => Theme::Atomic,
        _ => Theme::Netrunner,
    }
}

/// Set the active theme (the monitor's key handler only).
#[cfg(any(feature = "ebpf", test))]
pub(crate) fn set(theme: Theme) {
    ACTIVE.store(theme.index(), Ordering::Relaxed);
}

/// Pure cycle (the cosmostrix `cycle_color_scheme` contract): step
/// `dir` positions through the catalog with modulo wraparound in
/// both directions. Isolated so the wraparound math pins on its own;
/// the monitor only ever steps +1 since NIGHT-engrave-2 (one key),
/// and the negative direction stays available to the pins and any
/// future surface that needs it.
#[cfg(any(feature = "ebpf", test))]
#[must_use]
pub(crate) fn cycle_from(current: Theme, dir: i32) -> Theme {
    let n = THEMES.len() as i32;
    let idx = i32::from(current.index()) + dir;
    let wrapped = ((idx % n) + n) % n;
    THEMES[wrapped as usize]
}

/// Cycle the active theme one step (`+1` next, `-1` previous) and
/// return what it became.
#[cfg(any(feature = "ebpf", test))]
pub(crate) fn cycle(dir: i32) -> Theme {
    let next = cycle_from(active(), dir);
    set(next);
    next
}

/// The escape for one slot of one theme at one capability depth.
#[must_use]
pub(crate) fn escape_for(
    theme: Theme,
    slot: Slot,
    bold: bool,
    cap: ColorCapability,
) -> &'static str {
    let enc = table(theme, slot);
    match (cap, bold) {
        (ColorCapability::TrueColor, false) => enc.truecolor,
        (ColorCapability::TrueColor, true) => enc.truecolor_bold,
        (ColorCapability::Color256, false) => enc.color256,
        (ColorCapability::Color256, true) => enc.color256_bold,
        (ColorCapability::Color16, false) => enc.color16,
        (ColorCapability::Color16, true) => enc.color16_bold,
        (ColorCapability::Mono, _) => "",
    }
}

/// The escape for one slot of the ACTIVE theme at the probed
/// capability — the one entry point the color layer's builders call.
pub(crate) fn escape(slot: Slot, bold: bool) -> &'static str {
    escape_for(active(), slot, bold, capability())
}

