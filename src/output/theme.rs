//! Eagle-eyes theme catalog (NIGHT-boost-18, improve-27): six
//! palettes the live monitor cycles with `t` — the cosmostrix
//! cycle contract (modulo wraparound), one key, zero config
//! (NIGHT-engrave-2 retired the uppercase `T` twin at the owner's
//! "better only simple 't'" call: forward-only, wrapping).
//!
//! Scope (the owner's exact task wording): themes live INSIDE the
//! eagle-eyes monitoring mode. The theme state is a process-global
//! atomic that NOTHING outside the monitor's key handler ever
//! writes — so every other surface (help, errors, status, list-apps)
//! always renders the default and the CLI's byte output is
//! unchanged. `netrunner` IS that default, and its encodings are
//! byte-identical to the pre-theme constants (the regression pin in
//! test/output/theme_tests.rs holds this).
//!
//! Each theme defines five semantic slots — brand, ok, warn, hot,
//! grey — and each slot carries all three capability encodings
//! (TrueColor RGB, xterm-256 index, 16-color SGR) plus their bold
//! twins, all generated by the `slot!` macro from the same numbers
//! docs/BRANDING.md documents.
//!
//! NIGHT-boost-23 (the masterclass audit of the five non-default
//! themes) pinned the fallback contract the table now follows:
//!
//! - **Nearest-match where hue must read true**: the 256-depth
//!   indices for brand/ok slots are the nearest xterm cube matches
//!   (forest's leaf-green brand had rendered olive, carbon's pale
//!   mint ok had rendered saturated spring green at 28x the error;
//!   carbon's silver brand had dimmed to the grey-ramp's 188 —
//!   below its own 16-color fallback's hierarchy). Warn/hot slots
//!   keep the documented visibility precedent: the saturated corner
//!   wins over the exact match when the hue family holds
//!   (netrunner warn 220 / hot 196 unchanged).
//! - **The grey slot degrades to the neutral grey ramp (245 / bright
//!   black 90) in every theme** — subordinate text stays subordinate
//!   whatever the accent becomes, a uniform-tier contract that
//!   outranks nearest-match.
//! - **16-color distinctness within a theme is absolute**: no two
//!   slots share an SGR (forest brand/ok both drew 32 — the brand
//!   now takes bright green 92; atomic brand/warn both drew 33 — the
//!   brand now takes bright yellow 93). The brand takes the bright
//!   slot so the frame's identity outranks its data on every
//!   legacy terminal.
//!
//! Catalog order is the cycle order:
//! netrunner (default) -> night_cyber -> forest -> spaceflight ->
//! carbon -> atomic -> netrunner.

use std::sync::atomic::{AtomicU8, Ordering};

use super::color::{capability, ColorCapability};

/// The monitor's themes, in cycle order. Index 0 is the default.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Theme {
    /// The default: purple brand #A855F7, the pre-theme constants.
    Netrunner,
    /// Neon night city: cyan brand #00E5FF, magenta-red champion.
    NightCyber,
    /// Deep woodland: leaf-green brand #7CB342, burnt-orange heat.
    Forest,
    /// Cool altitude: pale-sky brand #4FC3F7, teal-green status.
    Spaceflight,
    /// Near-mono industrial: silver brand #D6D6D6, minimal accents.
    Carbon,
    /// Retro lab bench: atomic orange #FF6D00, vivid status green.
    Atomic,
}

/// The whole catalog, in cycle order. The cycle surface is
/// monitor-only (ebpf) plus the catalog pins (test): a build without
/// the monitoring feature renders the default and never cycles.
#[cfg(any(feature = "ebpf", test))]
pub(crate) const THEMES: [Theme; 6] = [
    Theme::Netrunner,
    Theme::NightCyber,
    Theme::Forest,
    Theme::Spaceflight,
    Theme::Carbon,
    Theme::Atomic,
];

impl Theme {
    /// Cycle position (the index into [`THEMES`]).
    #[cfg(any(feature = "ebpf", test))]
    const fn index(self) -> u8 {
        match self {
            Theme::Netrunner => 0,
            Theme::NightCyber => 1,
            Theme::Forest => 2,
            Theme::Spaceflight => 3,
            Theme::Carbon => 4,
            Theme::Atomic => 5,
        }
    }

    /// Catalog name (lowercase, the BRANDING.md spelling) — rendered
    /// by the footer's status line (`theme netrunner`, NIGHT-engrave-2)
    /// so every `t` press names what the frame now wears.
    #[cfg(any(feature = "ebpf", test))]
    pub(crate) const fn name(self) -> &'static str {
        match self {
            Theme::Netrunner => "netrunner",
            Theme::NightCyber => "night_cyber",
            Theme::Forest => "forest",
            Theme::Spaceflight => "spaceflight",
            Theme::Carbon => "carbon",
            Theme::Atomic => "atomic",
        }
    }

    /// The theme's brand RGB triple (the BRANDING.md numbers) — the
    /// eagle-eyes border gradient's ramp source (NIGHT-boost-20):
    /// the frame's side rails interpolate down the brand's own
    /// dark-bright-dark wave.
    #[cfg(any(feature = "ebpf", test))]
    pub(crate) const fn brand_rgb(self) -> (u8, u8, u8) {
        match self {
            Theme::Netrunner => (168, 85, 247),
            Theme::NightCyber => (0, 229, 255),
            Theme::Forest => (124, 179, 66),
            Theme::Spaceflight => (79, 195, 247),
            Theme::Carbon => (214, 214, 214),
            Theme::Atomic => (255, 109, 0),
        }
    }
}

/// The semantic slots a theme paints. Hot and Grey exist only in
/// the full build and the pins: their color-layer builders are
/// ebpf-gated (the champion and subordinate tiers render solely
/// inside the monitor).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Slot {
    Brand,
    Ok,
    Warn,
    #[cfg(any(feature = "ebpf", test))]
    Hot,
    #[cfg(any(feature = "ebpf", test))]
    Grey,
}

/// All six encodings of one slot: three capabilities x regular/bold.
struct SlotEncodings {
    truecolor: &'static str,
    truecolor_bold: &'static str,
    color256: &'static str,
    color256_bold: &'static str,
    color16: &'static str,
    color16_bold: &'static str,
}

/// Build one slot's encodings from the BRANDING.md numbers: the
/// TrueColor escapes are derived from the same RGB the docs carry,
/// so the table and the documentation cannot drift apart silently.
macro_rules! slot {
    ($r:expr, $g:expr, $b:expr, $idx256:expr, $sgr16:expr) => {
        SlotEncodings {
            truecolor: concat!(
                "\x1b[38;2;",
                stringify!($r),
                ";",
                stringify!($g),
                ";",
                stringify!($b),
                "m"
            ),
            truecolor_bold: concat!(
                "\x1b[1;38;2;",
                stringify!($r),
                ";",
                stringify!($g),
                ";",
                stringify!($b),
                "m"
            ),
            color256: concat!("\x1b[38;5;", stringify!($idx256), "m"),
            color256_bold: concat!("\x1b[1;38;5;", stringify!($idx256), "m"),
            color16: concat!("\x1b[", stringify!($sgr16), "m"),
            color16_bold: concat!("\x1b[1;", stringify!($sgr16), "m"),
        }
    };
}

