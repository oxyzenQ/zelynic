// --- Compile-time fold ------------------------------------------------

/// Const-evaluable digest of a masked layer: unmask word-by-word and
/// fold the clear bytes (up to `byte_len`, so zero padding never
/// participates) into the running FNV-1a 64-bit digest.
///
/// Input order and padding treatment are part of the contract — the
/// runtime recompute must traverse the identical byte stream.
const fn layer_fingerprint(words: &[u64], seed: u64, byte_len: usize) -> u64 {
    let mut hash = FNV1A64_OFFSET_BASIS;
    let mut emitted = 0usize;
    let mut i = 0usize;
    while i < words.len() {
        let clear = words[i] ^ mask_for(seed, i);
        let bytes = clear.to_le_bytes();
        let mut b = 0usize;
        while b < 8 && emitted < byte_len {
            hash ^= bytes[b] as u64;
            hash = hash.wrapping_mul(FNV1A64_PRIME);
            b += 1;
            emitted += 1;
        }
        i += 1;
    }
    hash
}

// --- Runtime materialization ------------------------------------------

/// Unmask a layer's words into clear bytes (zero-padded words truncated
/// to `byte_len`).
///
/// Callers pass the words and seed through `black_box` (see the
/// single-pass invariant in `provenance_view`): the unmask then reads
/// the artifact's real bytes and cannot be constant-folded.
fn unmask_to_bytes(words: &[u64], seed: u64, byte_len: usize) -> Vec<u8> {
    let mut out = Vec::with_capacity(words.len() * 8);
    for (i, word) in words.iter().enumerate() {
        let clear = *word ^ mask_for(seed, i);
        out.extend_from_slice(&clear.to_le_bytes());
    }
    out.truncate(byte_len);
    out
}

/// Runtime FNV-1a 64-bit fold over clear bytes (mirror of the const
/// fold's byte stream; used only on bytes already produced by one
/// unmask pass, never on fresh constant inputs, so there is nothing
/// here for LLVM to fold away).
fn fnv1a64_bytes(bytes: &[u8]) -> u64 {
    let mut hash = FNV1A64_OFFSET_BASIS;
    for byte in bytes {
        hash ^= *byte as u64;
        hash = hash.wrapping_mul(FNV1A64_PRIME);
    }
    hash
}

// --- Anchor payload framing -------------------------------------------

/// Frame the anchor payload: domain tag, then EACH layer's clear bytes
/// with a 64-bit little-endian length prefix. Byte-exact mirror of the
/// generator's `anchor_payload`; the length prefix keeps the layer
/// boundaries unambiguous, the domain tag keeps this payload distinct
/// from any other blake3 use in the tree.
fn anchor_payload(
    manifest_full_bytes: &[u8],
    manifest_dormant_bytes: &[u8],
    authors_bytes: &[u8],
) -> Vec<u8> {
    let mut out = Vec::with_capacity(
        ANCHOR_DOMAIN.len()
            + 24
            + manifest_full_bytes.len()
            + manifest_dormant_bytes.len()
            + authors_bytes.len(),
    );
    out.extend_from_slice(ANCHOR_DOMAIN);
    out.extend_from_slice(&(manifest_full_bytes.len() as u64).to_le_bytes());
    out.extend_from_slice(manifest_full_bytes);
    out.extend_from_slice(&(manifest_dormant_bytes.len() as u64).to_le_bytes());
    out.extend_from_slice(manifest_dormant_bytes);
    out.extend_from_slice(&(authors_bytes.len() as u64).to_le_bytes());
    out.extend_from_slice(authors_bytes);
    out
}

/// Recompute the anchor digest over the materialized clear bytes (the
/// blake3 crate's own implementation; the Python generator mirror is
/// vector-pinned to it).
fn anchor_digest(
    manifest_full_bytes: &[u8],
    manifest_dormant_bytes: &[u8],
    authors_bytes: &[u8],
) -> [u8; 32] {
    *blake3::hash(&anchor_payload(
        manifest_full_bytes,
        manifest_dormant_bytes,
        authors_bytes,
    ))
    .as_bytes()
}

/// Lowercase hex for the `b3:` renderings (`-V` anchor + `sig` report).
fn hex32(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        out.push_str(&format!("{byte:02x}"));
    }
    out
}

/// The ACTIVE manifest fingerprint (the `fp=` value on the
/// `Depth-matrix:` line), for the `sig` report's identity block. Which
/// manifest is active follows the same lane law as the Signature line.
#[must_use]
pub(crate) fn manifest_fingerprint() -> u64 {
    match super::ebpf_lane() {
        "dormant (not compiled)" => MANIFEST_DORMANT_FINGERPRINT,
        _ => MANIFEST_FINGERPRINT,
    }
}

// --- Identity binding -------------------------------------------------

/// Marker that separates the manifest's brand prose from the owner
/// identity. Plaintext is safe here: it contains no identity, and its
/// bytes are inside the manifests, hence bound by the fingerprints.
const MANIFEST_IDENTITY_MARKER: &str = "Official Build by ";

/// Year suffix the manifests carry after the identity. Generic text,
/// same binding rationale as the marker.
const MANIFEST_IDENTITY_YEAR: &str = " 2026";

/// Extract the owner identity core from a materialized manifest:
/// everything after the marker, minus the trailing year.
///
/// `None` means the manifest no longer carries the marker/year shape —
/// a tampering signal, not a panic path.
fn identity_core(manifest: &str) -> Option<&str> {
    manifest
        .split_once(MANIFEST_IDENTITY_MARKER)
        .map(|(_, tail)| tail)
        .and_then(|tail| tail.strip_suffix(MANIFEST_IDENTITY_YEAR))
}

/// The materialized authors string, computed once per process — the
/// footer surfaces (the status stamp, the eagle-eyes engraving) render
/// on every frame, and the unmask family must not run per frame. The
/// cache carries the SAME bytes the provenance pass verifies (the
/// single-pass invariant holds: one materialization feeds every
/// consumer).
#[must_use]
pub(crate) fn materialized_authors() -> &'static str {
    static CACHE: std::sync::OnceLock<String> = std::sync::OnceLock::new();
    CACHE.get_or_init(|| provenance_view().authors)
}

/// The identity text the surfaces render: the active manifest's
/// "Official Build by <identity> <year>" tail. Empty when the manifest
/// no longer carries the marker shape (a tampering signal the surfaces
/// render honestly instead of panicking on).
#[must_use]
pub(crate) fn identity_of(manifest: &str) -> String {
    manifest
        .split_once(MANIFEST_IDENTITY_MARKER)
        .map(|(_, tail)| tail.to_string())
        .unwrap_or_default()
}

// --- Version-report surface -------------------------------------------

/// Everything the `-V/--version` report and the `sig` report render
/// from the provenance layers: the lane-honest Signature-line manifest,
/// the Depth-matrix status line, and the Copyright-line authors string.
///
/// All three derive from ONE unmask pass per layer inside
/// `provenance_view` — the single-pass invariant. `info::version_body`
/// and the `sig` report must not unmask anything themselves; they
/// render these fields verbatim.
pub(crate) struct ProvenanceView {
    /// Full lane-honest manifest text for the `Signature:` line.
    pub manifest: String,
    /// `Depth-matrix:` line body (fingerprint + status + anchor + layers).
    pub depth_line: String,
    /// Authors text for the `Copyright:` line.
    pub authors: String,
    /// The runtime-recomputed anchor digest, lowercase hex (no `b3:`
    /// prefix — renderers add it). Equals `DEPTH_ANCHOR`'s hex exactly
    /// when `status=verified`.
    pub anchor_hex: String,
    /// The full verification verdict: fingerprints + binding + anchor.
    pub verified: bool,
}

/// Materialize the provenance layers and verify them, in one pass.
///
/// Verification is three-fold and ALL thirds must hold for
/// `status=verified`:
///
/// 1. Fingerprint: the runtime fold over the clear bytes equals the
///    embedded const digest for the ACTIVE manifest and the authors
///    layer. Catches any patched word on the surfaces the binary
///    actually displays.
/// 2. Binding: the identity core extracted from the active manifest is
///    a prefix of the authors string. Catches incoherent single-layer
///    rebrands (the identity claims disagree).
/// 3. Anchor: the blake3 recompute over the framed clear payload of
///    ALL THREE layers equals the embedded `DEPTH_ANCHOR`. The
///    cryptographic seal over the whole family at once — 256-bit
///    strength above the FNV-64 fingerprints, and the lane that is NOT
///    displayed stays sealed too.
///
/// Tampered bytes may not decode as UTF-8; `from_utf8_lossy` renders
/// replacement characters instead of panicking — the status line is the
/// honest signal, and a broken identity display next to `tampered` is
/// itself evidence.
#[must_use]
pub(crate) fn provenance_view() -> ProvenanceView {
    use std::hint::black_box;

    // One opaque read per layer: the words and seeds pass through
    // black_box, so the unmask below runs for real and every consumer
    // of `manifest` / `authors` downstream sees exactly these bytes.
    // BOTH manifests unmask on every build: the anchor binds both lanes
    // (a patched claim on either breaks the seal), and the lane choice
    // below picks only which manifest the surfaces DISPLAY.
    let manifest_full_bytes = unmask_to_bytes(
        black_box(&MASKED_MANIFEST_WORDS),
        black_box(MANIFEST_SEED),
        MANIFEST_BYTE_LEN,
    );
    let manifest_dormant_bytes = unmask_to_bytes(
        black_box(&MASKED_MANIFEST_DORMANT_WORDS),
        black_box(MANIFEST_DORMANT_SEED),
        MANIFEST_DORMANT_BYTE_LEN,
    );
    let authors_bytes = unmask_to_bytes(
        black_box(&MASKED_AUTHORS_WORDS),
        black_box(AUTHORS_SEED),
        AUTHORS_BYTE_LEN,
    );

    // The lane law (NIGHT-dinner-4, the contract this module inherits
    // from the former plaintext signature_line()): the dormant stamp —
    // and only it — flips the displayed claim.
    let (active_bytes, active_fp) = match super::ebpf_lane() {
        "dormant (not compiled)" => (
            manifest_dormant_bytes.as_slice(),
            MANIFEST_DORMANT_FINGERPRINT,
        ),
        _ => (manifest_full_bytes.as_slice(), MANIFEST_FINGERPRINT),
    };

    let active_fp_runtime = fnv1a64_bytes(active_bytes);
    let authors_fp_runtime = fnv1a64_bytes(&authors_bytes);
    let fingerprints_ok =
        active_fp_runtime == active_fp && authors_fp_runtime == AUTHORS_FINGERPRINT;

    let manifest = String::from_utf8_lossy(active_bytes).into_owned();
    let authors = String::from_utf8_lossy(&authors_bytes).into_owned();

    let binding_ok = identity_core(&manifest).is_some_and(|core| authors.starts_with(core));

    // D3 anchor: the SAME bytes just materialized feed the blake3
    // recompute over all three layers (single-pass invariant — no
    // second unmask, no separate display copy).
    let runtime_anchor = anchor_digest(
        &manifest_full_bytes,
        &manifest_dormant_bytes,
        &authors_bytes,
    );
    let anchor_ok = runtime_anchor == DEPTH_ANCHOR;

    let status = if fingerprints_ok && binding_ok && anchor_ok {
        "verified"
    } else {
        "tampered"
    };
    let depth_line = format!(
        "Depth-matrix: fp={active_fp:016x} status={status} anchor=b3:{} layers=d0:masked-words,d1:masked-words,d2:dual-fingerprint,d3:blake3-anchor",
        hex32(&runtime_anchor)
    );

    ProvenanceView {
        manifest,
        depth_line,
        authors,
        anchor_hex: hex32(&runtime_anchor),
        verified: status == "verified",
    }
}

